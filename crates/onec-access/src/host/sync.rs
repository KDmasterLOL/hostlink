//! Projection of hub agents into strict OpenSSH host blocks and known-host entries.

use super::*;
use crate::GatewayTrust;

/// Regenerates managed SSH host/trust configuration from the current hub agent inventory.
///
/// Agents without the required target SSH identity/trust metadata are reported as skipped rather
/// than projected insecurely. When `install_include` is true, the user's SSH config receives the
/// managed include entry.
///
/// # Errors
///
/// Returns [`crate::AppError`] when agent inventory, trust/key parsing, managed file publication,
/// private permissions, or optional user-config include installation fails.
pub async fn sync_hub_ssh_hosts(
    client: &HubClient,
    install_include: bool,
) -> AppResult<SshHostSyncReport> {
    let config = client.config();
    let identity = config.identity.as_deref().ok_or_else(|| {
        crate::invalid_config(
            "hostlink config needs `identity` before standard SSH hosts can be generated"
                .to_owned(),
        )
    })?;
    if !identity.is_file() {
        return Err(crate::not_found_error(format!(
            "operator SSH identity: {}",
            identity.display()
        )));
    }
    let gateways = client.gateway_routes().await?;
    let gateway_known_hosts = crate::managed_gateway_known_hosts_path()?;
    for gateway in &gateways {
        if let GatewayTrust::KnownHosts(path) = &gateway.trust
            && !path.is_file()
        {
            return Err(crate::not_found_error(format!(
                "gateway known_hosts: {}",
                path.display()
            )));
        }
    }

    let mut agents = client.list_agents().await?;
    agents.sort_by(|left, right| left.name.cmp(&right.name));
    let generated_config = managed_ssh_config_path()?;
    let target_known_hosts = managed_target_known_hosts_path()?;
    // Validate serialized OpenSSH paths before publishing any managed SSH files.
    ssh_path(&generated_config)?;
    let mut configured = Vec::new();
    let mut skipped = Vec::new();
    let mut host_blocks = String::new();
    let mut known_host_lines = String::new();
    let mut target_known_host_lines = String::new();

    host_blocks.push_str("# Generated by hostlink. Do not edit; run `hostlink sync-ssh`.\n");
    let mut gateway_aliases = Vec::with_capacity(gateways.len());
    for (index, gateway) in gateways.iter().enumerate() {
        let alias = gateway_alias(index);
        gateway_aliases.push(alias.clone());
        host_blocks.push_str(&format!("Host {alias}\n"));
        host_blocks.push_str(&format!(
            "    HostName {}\n    User {}\n    Port {}\n",
            ssh_scalar(&gateway.host)?,
            ssh_scalar(&gateway.user)?,
            gateway.port
        ));
        let known_hosts = match &gateway.trust {
            GatewayTrust::PinnedPublicKey(value) => {
                let key = russh::keys::ssh_key::PublicKey::from_openssh(value).map_err(|_| {
                    crate::invalid_config(format!(
                        "invalid hub gateway host key for {}:{}",
                        gateway.host, gateway.port
                    ))
                })?;
                if key.algorithm() != russh::keys::Algorithm::Ed25519 {
                    return Err(crate::invalid_config(format!(
                        "hub gateway host key for {}:{} must use Ed25519",
                        gateway.host, gateway.port
                    )));
                }
                let mut key = key;
                key.set_comment("");
                known_host_lines.push_str(&format!(
                    "{alias} {}\n",
                    key.to_openssh()
                        .map_err(|error| crate::invalid_config(format!(
                            "invalid hub gateway host key: {error}"
                        )))?
                ));
                host_blocks.push_str(&format!("    HostKeyAlias {alias}\n"));
                gateway_known_hosts.as_path()
            }
            GatewayTrust::KnownHosts(path) => path.as_path(),
        };
        append_common_security(
            &mut host_blocks,
            identity,
            known_hosts,
            null_known_hosts_path(),
        )?;
        host_blocks.push('\n');
    }

    for agent in &agents {
        let Some(username) = agent
            .username
            .as_deref()
            .filter(|value| !value.trim().is_empty())
        else {
            skipped.push(SshHostSkip {
                name: agent.name.clone(),
                reason: "missing Windows username; re-enroll this machine".to_owned(),
            });
            continue;
        };
        let Some(host_key) = agent
            .ssh_host_public_key
            .as_deref()
            .and_then(normalized_ed25519_public_key)
        else {
            skipped.push(SshHostSkip {
                name: agent.name.clone(),
                reason: "missing/invalid SSH host public key; re-enroll this machine".to_owned(),
            });
            continue;
        };
        if agent.name.eq_ignore_ascii_case(GATEWAY_ALIAS) {
            skipped.push(SshHostSkip {
                name: agent.name.clone(),
                reason: format!("name conflicts with reserved SSH alias {GATEWAY_ALIAS}"),
            });
            continue;
        }

        let host_key_alias = host_key_alias(agent);
        target_known_host_lines.push_str(&format!("{host_key_alias} {host_key}\n"));
        host_blocks.push_str(&format!(
            "Host {}\n",
            ssh_host_patterns(agent, &agents)?.join(" ")
        ));
        host_blocks.push_str("    HostName 127.0.0.1\n");
        host_blocks.push_str(&format!("    Port {}\n", agent.remote_port));
        host_blocks.push_str(&format!("    User {}\n", ssh_scalar(username)?));
        host_blocks.push_str(&format!("    ProxyJump {}\n", gateway_aliases[0]));
        host_blocks.push_str(&format!("    HostKeyAlias {host_key_alias}\n"));
        append_common_security(
            &mut host_blocks,
            identity,
            &target_known_hosts,
            null_known_hosts_path(),
        )?;
        host_blocks.push('\n');
        configured.push(agent.name.clone());
    }

    write_atomic(&gateway_known_hosts, known_host_lines.as_bytes())?;
    write_atomic(&target_known_hosts, target_known_host_lines.as_bytes())?;
    hostlink_core::restrict_private_file(&gateway_known_hosts)
        .map_err(crate::private_path_error)?;
    write_atomic(&generated_config, host_blocks.as_bytes())?;
    hostlink_core::restrict_private_file(&target_known_hosts).map_err(crate::private_path_error)?;
    hostlink_core::restrict_private_file(&generated_config).map_err(crate::private_path_error)?;

    let user_ssh_config = if install_include {
        let path = user_ssh_config_path()?;
        install_managed_include(&path, &generated_config)?;
        Some(path)
    } else {
        None
    };

    Ok(SshHostSyncReport {
        ssh_config: generated_config,
        target_known_hosts,
        user_ssh_config,
        configured_hosts: configured,
        skipped_hosts: skipped,
    })
}

pub(super) fn ssh_host_patterns(agent: &HubAgent, agents: &[HubAgent]) -> AppResult<Vec<String>> {
    let canonical = ssh_alias(&agent.name)?;
    let mut patterns = vec![canonical.clone()];

    let hostname = agent.hostname.trim();
    if hostname.is_empty() || hostname == canonical || hostname.eq_ignore_ascii_case(GATEWAY_ALIAS)
    {
        return Ok(patterns);
    }

    let Ok(hostname_alias) = ssh_alias(hostname) else {
        return Ok(patterns);
    };
    let conflicts = agents.iter().any(|other| {
        other.machine_id != agent.machine_id
            && (other.name.eq_ignore_ascii_case(&hostname_alias)
                || other.hostname.trim().eq_ignore_ascii_case(&hostname_alias))
    });
    if !conflicts {
        patterns.push(hostname_alias);
    }
    Ok(patterns)
}
